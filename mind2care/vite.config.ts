import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { defineConfig } from "@lovable.dev/vite-tanstack-config";

// The Cloudflare plugin only runs at build time, so `vite dev` never reads `.dev.vars`.
// Load it into process.env ourselves so server functions can read secrets locally.
// (.dev.vars is git-ignored; in production the key comes from a Cloudflare secret.)
function loadDevVars() {
  const file = resolve(process.cwd(), ".dev.vars");
  if (!existsSync(file)) return;
  for (const line of readFileSync(file, "utf8").split(/\r?\n/)) {
    const match = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/);
    if (!match || line.trim().startsWith("#")) continue;
    const value = match[2].replace(/^(['"])(.*)\1$/, "$2");
    if (process.env[match[1]] === undefined) process.env[match[1]] = value;
  }
}
loadDevVars();

export default defineConfig();
